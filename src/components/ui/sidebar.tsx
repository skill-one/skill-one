/**
 * The app's sidebar — `shadcn add sidebar`, trimmed to the one shape this app
 * uses: a fixed, always-visible column (`App` renders
 * `SidebarProvider > Sidebar + SidebarInset` and owns no collapse control).
 *
 * What the generated component carries and nothing here exercises is gone: the
 * open/closed state with its cookie and ⌘B binding, the mobile Sheet, the icon
 * rail, and the pieces no screen renders (trigger, rail, search input, group
 * action, menu action, skeleton, sub-menus, `useSidebar`). The selectors only
 * those could reach (`data-state`, `data-collapsible`, `data-variant`,
 * `peer-data-[variant=inset]`) went with them, so no class here waits on a
 * state no one sets.
 *
 * What remains keeps the upstream `data-slot`/`data-sidebar` attributes and
 * class strings verbatim, which keeps re-running the generator and re-applying
 * this trim a small diff.
 */

/** Width of the column; carried on the wrapper so the inset flows beside it. */
const SIDEBAR_WIDTH = "16rem"

function SidebarProvider({
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar-wrapper"
      style={
        {
          "--sidebar-width": SIDEBAR_WIDTH,
          ...style,
        } as React.CSSProperties
      }
      className={cn("flex min-h-svh w-full", className)}
      {...props}
    >
      {children}
    </div>
  )
}

function Sidebar({
  className,
  children,
  ...props
}: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar"
      className={cn(
        "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
        className
      )}
      {...props}
    >
      {children}
    </div>
  )
}

