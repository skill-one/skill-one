#!/usr/bin/env node
/**
 * Vendor the `skill-one/agents-info` dataset into this repo.
 *
 * Downloads `agents.jsonl` plus every repo-relative icon it references into
 * `public/agents/`, and generates `src/data/agent-icons.generated.ts` with:
 * the agent -> icon map and each icon's precomputed edge color (the same
 * `sqrt` average `fast-average-color` used to compute at runtime).
 *
 * Run: `pnpm sync:agents`
 *
 * The app then serves everything locally: no dataset download at runtime,
 * no runtime color analysis, full offline support.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const REPO = "skill-one/agents-info";
const REF = "HEAD";
const ORIGIN = `https://raw.githubusercontent.com/${REPO}/${REF}`;
const MIRROR = `https://cdn.jsdmirror.com/gh/${REPO}`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public", "agents");
const generatedPath = join(root, "src", "data", "agent-icons.generated.ts");

/** Fetch the first URL that answers OK. */
async function fetchFirst(urls) {
  let lastError;
  for (const url of urls) {
    try {
      const resp = await fetch(url);
      if (resp.ok) return resp;
      lastError = new Error(`HTTP ${resp.status} for ${url}`);
    } catch (err) {
      lastError = err;
    }
  }
  throw lastError;
}

/** Same parse rules as the former runtime loader: usable name + icon pair. */
function parseManifest(text) {
  const icons = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    try {
      const record = JSON.parse(trimmed);
      if (
        typeof record.name === "string" &&
        record.name.length > 0 &&
        typeof record.icon === "string" &&
        record.icon.length > 0
      ) {
        icons[record.name] = record.icon;
      }
    } catch {
      // Torn or foreign line: skip, keep the rest.
    }
  }
  return icons;
}

/**
 * The `sqrt` average from `fast-average-color` (its default algorithm),
 * over at most 100px per side like its canvas downscale: alpha-weighted
 * sum of squares, square-rooted. Transparent pixels fade out through
 * their alpha weight instead of darkening the mean.
 */
async function edgeColor(buffer) {
  const { data, info } = await sharp(buffer)
    .resize(100, 100, { fit: "inside" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let r = 0;
  let g = 0;
  let b = 0;
  let a = 0;
  const n = info.width * info.height;
  for (let i = 0; i < n; i++) {
    const alpha = data[i * 4 + 3];
    r += data[i * 4] ** 2 * alpha;
    g += data[i * 4 + 1] ** 2 * alpha;
    b += data[i * 4 + 2] ** 2 * alpha;
    a += alpha;
  }
  if (!a) return undefined;
  const hex = (v) => Math.round(Math.sqrt(v / a)).toString(16).padStart(2, "0");
  return `#${hex(r)}${hex(g)}${hex(b)}`;
}

const manifestResp = await fetchFirst([`${ORIGIN}/agents.jsonl`, `${MIRROR}/agents.jsonl`]);
const manifestText = await manifestResp.text();
const iconMap = parseManifest(manifestText);
const files = [...new Set(Object.values(iconMap).filter((icon) => !/^https:\/\//i.test(icon)))];

await mkdir(join(publicDir, "icons"), { recursive: true });
await writeFile(join(publicDir, "agents.jsonl"), manifestText);

const edgeColors = {};
for (const file of files) {
  const resp = await fetchFirst([`${ORIGIN}/${file}`, `${MIRROR}/${file}`]);
  const buffer = Buffer.from(await resp.arrayBuffer());
  await mkdir(join(publicDir, dirname(file)), { recursive: true });
  await writeFile(join(publicDir, file), buffer);
  const color = await edgeColor(buffer).catch(() => undefined);
  if (color) edgeColors[file] = color;
  console.log(`${file} -> ${color ?? "(no opaque pixels)"}`);
}

const syncedAt = new Date().toISOString().slice(0, 10);
const generated = `// Code generated by scripts/sync-agents-info.mjs — do not edit.
// Source: https://github.com/${REPO} (ref ${REF}, synced ${syncedAt}).
// Re-run \`pnpm sync:agents\` to pick up new agents or redrawn logos.

/** Agent name -> icon: a dataset-relative path under public/agents/. */
export const AGENT_ICON_MAP: Record<string, string> = ${JSON.stringify(iconMap, null, 2)};

/** Dataset-relative icon path -> precomputed edge (average) color. */
export const AGENT_EDGE_COLORS: Record<string, string> = ${JSON.stringify(edgeColors, null, 2)};
`;
await writeFile(generatedPath, generated);

console.log(
  `\n${Object.keys(iconMap).length} agents, ${files.length} icons, ` +
    `${Object.keys(edgeColors).length} edge colors -> ${generatedPath}`,
);
